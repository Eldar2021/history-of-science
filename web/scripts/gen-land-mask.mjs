/**
 * Build-time only: turns the world-atlas land polygons into a 1-degree land/sea bitmask.
 *
 * The globe draws land as a field of dots. Shipping the dots themselves would cost ~37 KB;
 * shipping this mask costs ~11 KB and lets the dot density change without regenerating data
 * (the component generates an even Fibonacci distribution and keeps the points that land here).
 *
 * Run: node scripts/gen-land-mask.mjs   (writes lib/globe/land.ts)
 * d3-geo, topojson-client and world-atlas are devDependencies for this script alone; nothing
 * in the browser bundle imports them.
 */
import { writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";
import topology from "world-atlas/land-50m.json" with { type: "json" };

const ROWS = 180; // one row per degree of latitude, north to south
const COLS = 360; // one column per degree of longitude, west to east

const land = feature(topology, topology.objects.land);

// One bit per cell. A cell counts as land if any of five samples falls on land: the centre
// and four points near the corners. Sampling the centre alone drops every coastal city into
// the sea (Alexandria, Miletus, Delft) and erases thin features - Britain, Japan, Italy's leg.
// Being generous by up to half a degree is invisible on a dotted globe; losing Sicily is not.
const OFFSETS = [[0, 0], [-0.4, -0.4], [0.4, -0.4], [-0.4, 0.4], [0.4, 0.4]];
const bytes = new Uint8Array((ROWS * COLS) / 8);
let landCells = 0;
for (let row = 0; row < ROWS; row++) {
  const lat = 90 - row - 0.5;
  for (let col = 0; col < COLS; col++) {
    const lng = col - 180 + 0.5;
    if (!OFFSETS.some(([dx, dy]) => geoContains(land, [lng + dx, lat + dy]))) continue;
    const bit = row * COLS + col;
    bytes[bit >> 3] |= 0x80 >> (bit & 7);
    landCells++;
  }
}

const base64 = Buffer.from(bytes).toString("base64");
writeFileSync(
  "lib/globe/land.ts",
  `// Generated by scripts/gen-land-mask.mjs from world-atlas land-50m. Do not edit by hand.
// ${ROWS} rows of latitude x ${COLS} columns of longitude, one bit per cell, land = 1.
// Row 0 is the northernmost band, column 0 starts at 180 degrees west.
export const LAND_ROWS = ${ROWS};
export const LAND_COLS = ${COLS};
export const LAND_MASK_BASE64 =
  "${base64}";
`,
);
console.log(`land cells: ${landCells} of ${ROWS * COLS} (${((landCells / (ROWS * COLS)) * 100).toFixed(1)}%)`);
console.log(`lib/globe/land.ts: ${(base64.length / 1024).toFixed(1)} KB of base64`);
